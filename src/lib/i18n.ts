const DICTS: Record<Lang, Dict> = { cs, sk, en };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: I18nKey, vars?: Vars): string {
  let s = DICTS[lang]?.[key] ?? cs[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

type PluralBase = "transfers" | "stops";

export function pluralForm(lang: Lang, n: number): "one" | "few" | "many" {
  if (n === 1) return "one";
  if (lang !== "en" && n >= 2 && n <= 4) return "few";
  return "many";
}

export function translatePlural(lang: Lang, base: PluralBase, n: number, vars?: Vars): string {
  return translate(lang, `${base}_${pluralForm(lang, n)}` as I18nKey, { n, ...vars });
}

